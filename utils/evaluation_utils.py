def calculate_metrics(results, top_k, task_type='mean_median'):
    true_positives = 0
    false_negatives = 0
    false_positives = 0
    true_negatives = 0

    # Generate column names based on task type and top_k
    pred_cluster_columns = []
    for i in range(1, top_k + 1):
        if task_type == 'mean_median':
            # Mean/Median clustering task uses ordinal suffixes
            if i == 1:
                pred_cluster_columns.append(f'1st_pred_cluster')
            elif i == 2:
                pred_cluster_columns.append(f'2nd_pred_cluster')
            elif i == 3:
                pred_cluster_columns.append(f'3rd_pred_cluster')
            else:
                pred_cluster_columns.append(f'{i}th_pred_cluster')
        elif task_type == 'classification':
            # Classification task uses simple numerical suffixes with 'st'
            pred_cluster_columns.append(f'{i}st_pred_cluster')

    for index, result in results.iterrows():
        gt_cluster = result['gt_relationship']
        # Get the top_k predicted clusters using dynamic column names
        pred_clusters = [result[column] for column in pred_cluster_columns if column in result]

        if gt_cluster in pred_clusters:
            true_positives += 1
        else:
            false_negatives += 1
            false_positives += 1

        for cluster_id in range(1, 54):
            if cluster_id != gt_cluster and cluster_id not in pred_clusters:
                true_negatives += 1

    # Print and calculate metrics
    print(f'TP: {true_positives}')
    print(f'FN: {false_negatives}')
    print(f'FP: {false_positives}')
    print(f'TN: {true_negatives}')

    precision = true_positives / (true_positives + false_positives) if (true_positives + false_positives) > 0 else 0
    recall = true_positives / (true_positives + false_negatives) if (true_positives + false_negatives) > 0 else 0
    f1_score = 2 * (precision * recall) / (precision + recall) if (precision + recall) > 0 else 0
    accuracy = (true_positives + true_negatives) / (true_positives + true_negatives + false_positives + false_negatives) if (true_positives + true_negatives + false_positives + false_negatives) > 0 else 0

    print(f'Precision: {precision}')
    print(f'Recall: {recall}')
    print(f'F1 Score: {f1_score}')
    print(f'Accuracy: {accuracy}')

    return precision, recall, f1_score, accuracy

def evaluate_embedding_models(df, model_name):
    df['is_tp_top5'] = df.apply(lambda row: row['original_cluster'] in row[['1st_best_cluster', '2nd_best_cluster', '3rd_best_cluster', '4th_best_cluster', '5th_best_cluster']].values, axis=1)
    tp_count_top5 = df['is_tp_top5'].sum()
    fp_count_top5 = len(df) - tp_count_top5
    accuracy_top5 = tp_count_top5 / len(df) * 100

    df['is_tp_top3'] = df.apply(lambda row: row['original_cluster'] in row[['1st_best_cluster', '2nd_best_cluster', '3rd_best_cluster']].values, axis=1)
    tp_count_top3 = df['is_tp_top3'].sum()
    fp_count_top3 = len(df) - tp_count_top3
    accuracy_top3 = tp_count_top3 / len(df) * 100

    df['is_tp_top1'] = df.apply(lambda row: row['original_cluster'] in row[['1st_best_cluster']].values, axis=1)
    tp_count_top1 = df['is_tp_top1'].sum()
    fp_count_top1 = len(df) - tp_count_top1
    accuracy_top1 = tp_count_top1 / len(df) * 100

    print(f"Considering {model_name} Top 5 Clusters:")
    print(f"True Positives (TP) : {tp_count_top5}")
    print(f"False Positives (FP): {fp_count_top5}")
    print(f"F1-score: {accuracy_top5:.2f}% \n")

    print(f"Considering {model_name} Top 3 Clusters:")
    print(f"True Positives (TP) : {tp_count_top3}")
    print(f"False Positives (FP): {fp_count_top3}")
    print(f"F1-score: {accuracy_top3:.2f}% \n")

    print(f"Considering {model_name} Top 1 Cluster:")
    print(f"True Positives (TP) : {tp_count_top1}")
    print(f"False Positives (FP): {fp_count_top1}")
    print(f"F1-score: {accuracy_top1:.2f}% \n")